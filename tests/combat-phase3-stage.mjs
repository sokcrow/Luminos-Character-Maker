import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const source = fs.readFileSync('js/combat-v073-stage.js', 'utf8');
const window = { document: { getElementById: () => null }, LuminousCombatLiveAdapter073: {state:{role:'dm'}} };
vm.runInNewContext(source, { window });
const stage = window.LuminousCombatStage073;
const point = (...args) => JSON.parse(JSON.stringify(stage.placementPoint(...args)));
assert.deepEqual(point(500, 600, {left:0,top:0,width:1000,height:1000}), {x:50,y:40});
// Same logical point in differently sized/translated/scaled browser fields.
assert.deepEqual(point(350, 480, {left:100,top:180,width:500,height:500}), {x:50,y:40});
assert.deepEqual(point(390 * .5, 844 * .6, {left:0,top:0,width:390,height:844}), {x:50,y:40});
assert.deepEqual(point(-100, 5000, {left:0,top:0,width:1000,height:1000}), {x:5,y:12});
assert.deepEqual(point(5000, -100, {left:0,top:0,width:1000,height:1000}), {x:95,y:52});
assert.ok(stage.depthAt(18).scale > stage.depthAt(52).scale);
assert.ok(stage.depthAt(18).order > stage.depthAt(52).order);
assert.ok(stage.depthAt(42,200,1000).order > stage.depthAt(42,0,1000).order);
const clean = {estado:{phase:'PRE_COMBAT_PLANNING'}};
assert.equal(stage.canPlace(clean),true);
for(const extra of [{authority:{current:{phase:'sealed'}}},{authority:{current:{phase:'complete'}}},{plannedActions:{a:{}}},{readyPlayers:{a:{ready:false}}},{estado:{phase:'COMBAT'}}]) assert.equal(stage.canPlace({...clean,...extra}),false);
const unit = {hp:37,sp:-2,statusEffects:{bleed:{count:2}},x:18,y:42};
const patched = stage.patchPlacement(unit,{x:60,y:20});
assert.equal(unit.x,18); assert.equal(patched.x,60); assert.equal(patched.y,20);
assert.equal(patched.hp,37); assert.equal(patched.sp,-2); assert.equal(patched.statusEffects,unit.statusEffects);
assert.equal(patched.positionPinned,true); assert.equal(patched.stagePlacement.revision,1);
assert.equal(stage.patchPlacement(patched,{x:61,y:20}).stagePlacement.revision,2);
// Actual camera output: layers move at different rates, ground exactly follows field.
const layers=[.18,.52,1,1.04].map(depth=>({dataset:{depth},style:{}}));
window.document.querySelectorAll=()=>layers;
stage.camera({x:-200,y:-100,scale:2});
assert.equal(layers[2].style.transform,'translate(-200px,-100px) scale(2)');
assert.equal(layers[0].style.transform,'translate(-36px,-18px) scale(1.18)');
window.matchMedia=()=>({matches:true});stage.camera({x:-200,y:-100,scale:2});
assert.ok(layers.every(layer=>layer.style.transform===layers[2].style.transform));
// Zero anchors remain zero; viewport size comes from the active field.
const live=fs.readFileSync('combat/source/combat-v073-live.html','utf8');
const start=live.indexOf('function unitBaseCombatAnchor('), end=live.indexOf('function unitCombatAnchor(',start);
const context={innerWidth:1600,innerHeight:900,$:()=>({offsetWidth:800,offsetHeight:500})};
vm.createContext(context);vm.runInContext(live.slice(start,end),context);
assert.deepEqual(JSON.parse(JSON.stringify(context.unitBaseCombatAnchor({x:0,y:0}))),{x:0,y:500});
assert.deepEqual(JSON.parse(JSON.stringify(context.unitBaseCombatAnchor({x:50,y:40}))),{x:400,y:300});
console.log('Phase 3: viewport-invariant flat positioning, depth ordering, camera/reduced motion, initial-formation boundaries and zero anchors passed');
