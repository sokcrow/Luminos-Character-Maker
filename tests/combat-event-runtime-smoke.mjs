import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
for (const name of ['status-library','status-engine','trait-engine','trait-catalog-core','archetype-engine','archetype-trait-catalog','fighter-maneuver-catalog','fighter-class-runtime','battle-master-archetype-runtime','combat-event-runtime']) await import(`../js/${name}.js`);
const g=globalThis,events=g.LuminousCombatEventRuntime,bm=g.LuminousBattleMasterArchetypeRuntime;
const loaded=[];
g.LuminousClassRuntimeBootstrap={async boot({character}){loaded.push(character.id);bm.install();return {ok:true}}};
const fighter=(id,maneuvers=[])=>({id,hp:100,maxHp:100,sp:0,faction:'ally',classes:[{classId:'fighter',levels:15}],characterBuild:{archetypes:[{classId:'fighter',archetypeId:'battle_master'}],maneuvers:{battle_master:maneuvers}}});
const plain=fighter('plain'),ambush=fighter('ambush',['ambush','tactical_assessment']);
const item={instanceId:'equipped',quantity:1,weapon_details:{effects:[{tag:'[Combat Start]',type:'status',target:'self',status:'protection',count:2}]}};
ambush.equipment={mainHand:item,offHand:item};
ambush.inventario_activo={equipped:item,bag:{instanceId:'bag',effects:[{type:'status',trigger:'encounter_start',status:'haste',count:99}]}};
const backup={...fighter('backup',['ambush']),isBackup:true,battleActive:false};
const enemy={id:'enemy',faction:'enemy',hp:100,maxHp:100};
const original=[plain,ambush,enemy,backup];
const planned=await events.planEncounterStart(original,{encounterId:'one',engine:{randomIntInclusive:()=>0}});
assert.equal(planned.started,3);
assert.equal(ambush.resources,undefined,'Planning is atomic: live units are untouched');
const [p,a,e,b]=planned.units;
assert.equal(p.resources.superiority,0);
assert.equal(p.statusEffects.superiority.count,0,'Superiority remains present at zero');
assert.equal(g.LuminousStatusLibrary.get('superiority').allowZeroCount,true);
assert.equal(p.statusEffects.second_wind.count,1,'Class runtime executes from resolved grants');
assert.equal(a.resources.superiority,10);
assert.equal(a.statusEffects.haste.count,5);
assert.equal(a.statusEffects.clash_power_up.count,2);
assert.equal(a.statusEffects.protection.count,2,'An equipped instance applies once across two slots');
assert.equal(p.statusEffects.clash_power_up.count,1,'Tactical Assessment targets the full allied roster');
assert.equal(e.statusEffects?.clash_power_up,undefined);
assert.equal(b.resources,undefined,'Reserves do not activate on the field');
assert.equal(loaded.includes('backup'),false);
events.notify('[On Hit]',p);events.notify('[Clash Win]',p);
assert.equal(p.resources.superiority,4,'Live hit and resolved Clash produce the authored gains');
bm.setSuperiorityCount(p,0);assert.equal(p.statusEffects.superiority.count,0);
const restored=JSON.parse(JSON.stringify(planned.units));
const repeated=await events.planEncounterStart(restored,{encounterId:'one'});
assert.equal(repeated.started,0,'Reloaded snapshots never rerun startup');
assert.equal(repeated.units[1].statusEffects.haste.count,5);
const next=await events.planEncounterStart(restored,{encounterId:'two',engine:{randomIntInclusive:()=>0}});
assert.equal(next.started,3,'A distinct encounter activates again');
assert.equal(next.units[1].resources.superiority,10);
// Canonical equipment traits and all trigger aliases share the same dispatcher.
const gearUnit={id:'gear',hp:10,maxHp:100,sp:0,equipment:{armor:{instanceId:'armor',traitDefinitions:[{id:'ward',effects:[{trigger:'on_combat_start',operations:[{type:'apply_status',statusId:'haste',count:3}]}]}]}}};
const gear=await events.planEncounterStart([gearUnit],{encounterId:'gear'});
assert.equal(gear.units[0].statusEffects.haste.count,3);
assert.equal(events.normalizeTrigger('[On Encounter Start]'),'encounter_start');
// The old engine's public start method delegates to exactly the same path.
vm.runInThisContext(fs.readFileSync(new URL('../js/combatEngine.js',import.meta.url),'utf8'));
const engine=vm.runInThisContext("CombatEngine");
const direct=[fighter('direct')];
await engine.triggerEncounterStart(direct,{encounterId:'direct'});
assert.equal(direct[0].statusEffects.superiority.count,0);
events.notify('[On Hit]',direct[0]);
await engine.triggerEncounterStart(direct,{encounterId:'direct'});
assert.equal(direct[0].resources.superiority,1);
const liveSource=fs.readFileSync(new URL('../combat/source/combat-v073-live.html',import.meta.url),'utf8');
const hook=liveSource.slice(liveSource.indexOf('function applySkillStatusEffects('),liveSource.indexOf('function setStatus(v)'));
let rendered=0;
vm.runInNewContext(hook+";applySkillStatusEffects({ownerId:'plain',plan:{data:{}}},null,'[On Hit]');applySkillStatusEffects({ownerId:'plain',plan:{data:{}}},null,'[Clash Win]');",{
  window:{LuminousCombatEventRuntime:events},combatData:{plain:p},skillEffectRows:()=>[],normalizeElement:()=>'',isSpellSkill:()=>false,renderStatusEffects(){rendered++}
});
assert.equal(p.resources.superiority,4,'The actual live viewer event hook reaches the resource adapter');
assert.equal(rendered,2,'Count changes refresh the real Status HUD');
console.log('Universal Encounter Start: class, archetype, equipment, zero-count resource, real event gains, atomic drafts and reload idempotence passed.');
