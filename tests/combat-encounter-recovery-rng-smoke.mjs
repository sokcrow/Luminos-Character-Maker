import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const read=file=>fs.readFileSync(new URL('../'+file,import.meta.url),'utf8');
for(const checkpointCursor of [undefined,0,7]){
  const units={fighter:{id:'fighter',hp:100,maxHp:100,sp:0,resources:{superiority:10},combatEventState:{encounterStarted:'rng'}}};
  const initial=JSON.stringify(units),execution=JSON.stringify({units,queue:[],resolvedKeys:[]});
  let current={id:'old',encounterId:'rng',round:1,phase:'running',seed:12345,encounterStart:{rngCursor:3},initialStateJson:initial,initialExecutionJson:execution,playback:{schemaVersion:1,session:'other-tab'}};
  if(checkpointCursor!==undefined)current.checkpoint={seq:1,actionSeq:1,eventCursor:5,rngCursor:checkpointCursor,stateJson:initial,executionJson:execution};
  const db={ref(){return {on(){},off(){},async set(){},async transaction(update){const result=update(current);assert.ok(result);current=result;return {committed:true,snapshot:{val:()=>result}}}}}};
  const c=vm.createContext({console,Math:Object.create(Math),Date,JSON,Map,Set,WeakMap,Promise,Uint32Array,addEventListener(){},setTimeout(){return 1},clearTimeout(){}});c.window=c;
  c.LuminousCombatLiveAdapter073={state:{role:'dm',round:1,uid:'dm',db}};
  c.LuminousCombat073={combatants:()=>units,render(){}};
  c.LuminousCombatStepRuntime={capturePresentation(){}};
  c.LuminousCombatPlayback={schemaVersion:1,engineVersion:'test'};
  vm.runInContext(read('js/combat-v073-authority.js'),c);
  const original=c.LuminousCombatAuthority073;original.state.current=current;
  const expectedCursor=checkpointCursor??3;
  original.resetRandom(current.seed,expectedCursor);
  const expected=Array.from({length:4},()=>original.random());
  original.resetRandom(current.seed,0);
  let resumes=0;
  const authority={...original,async requestStartRound(){resumes++;return true}};
  vm.runInContext(read('js/combat-v073-playback-sync.js'),c);
  c.LuminousCombatPlaybackSync.state.authority=authority;
  assert.equal(await c.LuminousCombatPlaybackSync.recover(),true);
  assert.equal(authority.state.cursor,expectedCursor,'Checkpoint cursor wins, including explicit zero; otherwise use startup cursor');
  assert.deepEqual(Array.from({length:4},()=>original.random()),expected,'Recovery continues the actual authoritative RNG sequence');
  assert.equal(units.fighter.resources.superiority,10,'Startup effects are restored, not re-granted');
  assert.equal(authority.state.resumeRuntime.units.fighter.resources.superiority,10);
  assert.equal(resumes,1);
}
console.log('Encounter recovery RNG: startup fallback, explicit zero checkpoint and later checkpoint preserve the original random sequence.');
