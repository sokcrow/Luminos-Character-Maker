import {test,expect} from '@playwright/test';
import {mountDirector} from './helpers/dm-director-fixture.mjs';
test.use({screenshot:'only-on-failure',trace:'retain-on-failure'});
const sizes=[[360,800],[390,844],[844,390],[768,1024],[1280,720],[1920,1080]];
for(const [width,height] of sizes){
 test(`Approved prototype, real flows and return to viewer ${width}x${height}`,async({page},info)=>{
  const errors=[];page.on('pageerror',error=>errors.push(error.message));
  await page.setViewportSize({width,height});await mountDirector(page);
  const root=page.getByRole('dialog',{name:'Director de Teatro',exact:true});
  await expect(root).toBeVisible();
  const mobile=width<=820||(width<=900&&height<=470);
  await expect(root.getByRole('heading',{name:'Personajes jugadores',exact:true})).toBeVisible();
  await expect(root.getByRole('heading',{name:'NPC / Otros',exact:true})).toBeVisible();
  const close=root.getByRole('button',{name:'Cerrar Director',exact:true});
  const bounds=await close.boundingBox();expect(bounds.width).toBeGreaterThanOrEqual(44);expect(bounds.height).toBeGreaterThanOrEqual(44);
  expect(bounds.x).toBeGreaterThanOrEqual(0);expect(bounds.x+bounds.width).toBeLessThanOrEqual(width);
  expect(await close.evaluate(el=>{const r=el.getBoundingClientRect();return el.contains(document.elementFromPoint(r.x+r.width/2,r.y+r.height/2));})).toBe(true);
  await page.screenshot({path:info.outputPath(`theatre-cast-${width}x${height}.png`)});
  await root.getByRole('button',{name:'Hablar como Aldara',exact:true}).click();
  const composer=page.getByRole('dialog',{name:'Escribir intervención de Teatro',exact:true});
  await expect(composer).toBeVisible();await page.locator('#theatre-dialogue-input').fill('Mensaje desde el prototipo');
  await page.locator('#btn-send-dialogue').click();await expect(page.locator('#theatre-dialogue-input')).toHaveValue('');
  expect(await page.evaluate(()=>window.writeId)).toBe(1);
  await page.screenshot({path:info.outputPath(`composer-${width}x${height}.png`)});
  await composer.getByRole('button',{name:'Cerrar compositor',exact:true}).click();
  if(mobile)await root.getByRole('tab',{name:'Registro',exact:true}).click();
  await expect(page.locator('#theatre-log-container .dialogue-row')).toHaveCount(2);
  await page.screenshot({path:info.outputPath(`theatre-log-${width}x${height}.png`)});
  if(mobile)await root.getByRole('tab',{name:'Dirección',exact:true}).click();
  await root.getByRole('button',{name:'Gestionar elenco',exact:true}).click();
  const utility=page.getByRole('dialog',{name:'Herramientas de escena',exact:true});await expect(utility).toBeVisible();
  await utility.locator('.btn-show').click();await expect(utility.locator('.actor-control-card')).toHaveAttribute('data-visible','true');
  await utility.locator('.btn-hide').click();await expect(utility.locator('.actor-control-card')).toHaveAttribute('data-visible','false');
  await utility.getByRole('button',{name:'Biblioteca',exact:true}).click();
  await utility.getByRole('button',{name:'Añadir al elenco: Sin imagen',exact:true}).click();
  await expect(utility.getByRole('status').filter({hasText:'Personaje añadido'})).toBeVisible();
  await utility.getByRole('button',{name:'En escena',exact:true}).click();
  const noSprite=utility.locator('.actor-control-card').filter({hasText:'Sin imagen'});await expect(noSprite.locator('.btn-show')).toBeDisabled();
  await noSprite.locator('.btn-remove').click();
  expect(await page.evaluate(()=>window.testRead('campaña/base_datos_npcs/nosprite')?.nombre)).toBe('Sin imagen');
  await utility.getByRole('button',{name:'Cerrar herramientas',exact:true}).click();
  await root.getByRole('button',{name:'Ambiente',exact:true}).click();
  const audio=page.getByRole('dialog',{name:'Music Director',exact:true});await expect(audio).toBeVisible();
  await audio.getByRole('button',{name:'Reproducir In Hell We Live, Lament — Instrumental',exact:true}).click();
  await expect.poll(()=>page.evaluate(()=>window.testRead('campaña/audio_director/music')?.active)).toBe(true);
  await audio.getByRole('button',{name:'Pausar',exact:true}).click();
  await expect.poll(()=>page.evaluate(()=>window.testRead('campaña/audio_director/music')?.active)).toBe(false);
  await page.screenshot({path:info.outputPath(`music-${width}x${height}.png`)});
  if(width<=960){
   await audio.getByRole('button',{name:'Mezclador',exact:true}).click();await expect(audio.getByRole('slider',{name:'Volumen de efectos',exact:true})).toBeVisible();
   await audio.getByRole('button',{name:'Biblioteca',exact:true}).click();
  }
  await audio.getByRole('tab',{name:/Mis archivos|Archivos/}).click();
  await expect(audio.getByRole('button',{name:'Subir archivos',exact:true})).toBeDisabled();
  await audio.getByText('Conectar biblioteca',{exact:true}).click();await expect(audio.getByRole('textbox',{name:'Dirección de biblioteca',exact:true})).toBeVisible();
  await page.screenshot({path:info.outputPath(`files-${width}x${height}.png`)});
  await audio.getByRole('button',{name:'Volver a Teatro',exact:true}).click();
  await close.click();await expect(root).not.toBeVisible();
  await expect(page.locator('#modulo-teatro>.stage-view-wrapper')).toBeVisible();
  expect(await page.evaluate(()=>document.querySelector('.theatre-dm-menu').open)).toBe(false);
  await page.locator('.theatre-dm-menu-toggle').click();await expect(root).toBeVisible();
  await page.keyboard.press('Escape');await expect(root).not.toBeVisible();
  await page.locator('.theatre-dm-menu-toggle').click();await expect(root).toBeVisible();
  if(mobile)await root.getByRole('tab',{name:'Dirección',exact:true}).click();
  await root.getByRole('button',{name:'Ver escena',exact:true}).click();await expect(root).not.toBeVisible();
  expect(await page.evaluate(()=>document.querySelectorAll('#theatre-stage').length)).toBe(1);
  expect(await page.evaluate(()=>document.documentElement.scrollWidth)).toBeLessThanOrEqual(width+1);
  expect(errors).toEqual([]);
 });
}
