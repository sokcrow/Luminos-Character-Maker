import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
await import('../js/combat-deployment-runtime.js');
await import('../js/combat-session-lifecycle.js');
await import('../js/combat-participants.js');
const d=globalThis.LuminousCombatDeploymentRuntime;
const unit=(id,size='medium',extra={})=>({id,size,faction:'enemy',hp:10,maxHp:10,battleActive:true,...extra});
for(const [size,cost] of Object.entries({tiny:.5,small:1,medium:1,large:1,huge:2,gargantuan:3}))assert.equal(d.fieldSpace(unit(size,size)),cost);
assert.equal(d.sizeOf({mechanics:{size:'Huge'}}),'huge');
assert.equal(d.sizeOf({size:'Pequeño'}),'small');
assert.equal(d.sizeOf({size:'unknown'}),'medium');
for(const extra of [{isSummon:true},{kind:'summon'},{isBackgroundUnit:true},{kind:'background_unit'}])assert.equal(d.fieldSpace(unit('summon','gargantuan',extra)),0);
const full=Object.fromEntries(Array.from({length:8},(_,i)=>['m'+i,unit('m'+i)]));
assert.equal(d.fieldCount(full,'enemy'),8);
assert.equal(d.canEnterField(full,'enemy',8,unit('tiny','tiny')),false);
assert.equal(d.canEnterField(full,'enemy',8,unit('summon','gargantuan',{isSummon:true})),true);
delete full.m7;
full.tiny=unit('tiny','tiny');
assert.equal(d.fieldSpaceUsed(full,'enemy'),7.5);
assert.equal(d.canEnterField(full,'enemy',8,unit('tiny2','tiny')),true);
assert.equal(d.canEnterField(full,'enemy',8,unit('large','large')),false);
const reserves={big:d.markBackup(unit('big','huge'),{queueOrder:1}),incoming:d.markBackup(unit('incoming','tiny'),{queueOrder:2})};
assert.equal(d.nextBackup(reserves,'enemy',full).key,'incoming','A waiting oversized body cannot overflow the side or block a fitting reserve');
assert.equal(d.nextBackup({big:reserves.big},'enemy',full),null);

// Canonical transactional deployment routes each new body against the updated budget.
let root={estado:{phase:'PLANNING',round:2},combatants:{},reserves:{}};
const db={ref(){return {on(_event,fn){fn({val:()=>root})},off(){},async transaction(fn){const next=fn(root);if(next===undefined)return {committed:false,snapshot:{val:()=>root}};root=next;return {committed:true,snapshot:{val:()=>structuredClone(root)}}}}}};
const tinyUnits=Array.from({length:17},(_,i)=>unit('tiny'+i,'tiny'));
const saved=await globalThis.LuminousCombatSession.deploy({db,units:tinyUnits});
assert.equal(saved.filter(u=>!u.isBackup).length,16);
assert.equal(saved[16].isBackup,true);
assert.equal(d.fieldSpaceUsed(root.combatants,'enemy'),8);
const [summon]=await globalThis.LuminousCombatSession.deploy({db,units:[unit('summon','huge',{isSummon:true})]});
assert.equal(summon.isBackup,false);
assert.equal(d.fieldSpaceUsed(root.combatants,'enemy'),8);
root={estado:{phase:'PLANNING',round:2},combatants:{},reserves:{}};
const giants=await globalThis.LuminousCombatSession.deploy({db,units:[unit('g1','gargantuan'),unit('g2','gargantuan'),unit('h','huge'),unit('large','large')]});
assert.equal(giants[3].isBackup,true);
assert.equal(d.fieldSpaceUsed(root.combatants,'enemy'),8);
const points=d.formationPoints(tinyUnits.slice(0,16),'enemy');
assert.equal(new Set(Object.values(points).map(p=>p.x+':'+p.y)).size,16,'Tiny bodies cannot pile onto the last fixed slot');
assert.equal(points.tiny0.y,points.tiny1.y);
assert.equal(Math.abs(points.tiny0.x-points.tiny1.x),4.5,'Two Tiny bodies share one normal-width cell');
assert.deepEqual(points,d.formationPoints(tinyUnits.slice(0,16),'enemy'),'Formation is deterministic on every client');
const mixed=[unit('g','gargantuan'),unit('h','huge'),unit('l','large'),unit('t','tiny'),unit('t2','tiny'),unit('m'),unit('s','huge',{isSummon:true})];
const mixedPoints=d.formationPoints(mixed,'enemy');
assert.equal(new Set(Object.values(mixedPoints).map(p=>p.x+':'+p.y)).size,mixed.length);
assert.ok(mixedPoints.s.y>mixedPoints.g.y);

// Real live adapter resolves legacy size fields and reacts to size-only updates.
const context={window:null,console,addEventListener(){},LuminousCombatDeploymentRuntime:d,LuminousCombatParticipants:globalThis.LuminousCombatParticipants};context.window=context;
vm.runInNewContext(fs.readFileSync('js/combat-v073-live-adapter.js','utf8'),context);
const adapter=context.LuminousCombatLiveAdapter073;
adapter.state.combatants={g:unit('g','huge',{scale:1.4}),t:unit('t','tiny')};
const normalized=adapter.normalizedCombatants();
assert.equal(normalized[0].size,'huge');assert.equal(normalized[0].scale,1.4,'Manual art scale is preserved and never multiplied twice');
const before=adapter.hydrationSignature(normalized,null);
adapter.state.combatants.g.size='gargantuan';
assert.notEqual(adapter.hydrationSignature(adapter.normalizedCombatants(),null),before);
adapter.state.combatants.g.positionPinned=true;adapter.state.combatants.g.x=63;adapter.state.combatants.g.y=20;
assert.equal(adapter.normalizedCombatants()[0].x,63,'DM pinned placements survive size-aware formation');
// Live reserve bridge checks the incoming body's cost, rather than assuming one slot.
const bridgeState={role:'dm',round:2,combatants:structuredClone(full)};
globalThis.LuminousCombatLiveAdapter073={state:bridgeState,hydrateNow:()=>true};
globalThis.LuminousCombat073={combatants:()=>bridgeState.combatants};
await import('../js/combat-v073-deployment-bridge.js');
const bridge=globalThis.LuminousCombatDeploymentBridge073;
bridge.setReserveCache(structuredClone(reserves));
assert.equal(bridge.promoteNextBackup('enemy').key,'incoming');
assert.equal(d.fieldSpaceUsed(bridgeState.combatants,'enemy'),8);
assert.equal(bridge.promoteNextBackup('enemy').promoted,false);
assert.ok(bridge.state.reserves.big,'Oversized backup remains queued');
bridge.stop();
console.log('Creature spaces: weighted transaction, 16 Tiny, summon exemption, reserve fit, deterministic formation, aliases and live hydration passed.');
