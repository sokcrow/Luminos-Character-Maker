/* Real shared-weapon-link regression tests: Theatre preview and Combat planner share API. */
const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");
const link = require("../js/item-enchantment-combat-link.js");
const blade = {instanceId:"sw1",definitionId:"longsword",category:"weapon",damageType:"slash",name:"Espada",quantity:1};
const mace = {instanceId:"mc1",definitionId:"mace",category:"weapon",damageType:"blunt",name:"Maza",quantity:1};
const dagger = {instanceId:"dg1",definitionId:"dagger",category:"weapon",damageType:"pierce",quantity:1};
const unit = {equipment:{mainHand:blade},inventario_activo:{blade}};
const slash = {id:"slash",type:"Attack",damageType:"cortante",sourceType:"skill"};
const blunt = {id:"blunt",type:"Attack",damageType:"contundente",sourceType:"skill"};
const pierce = {id:"pierce",type:"Attack",damageType:"piercing",isItemSkill:true};
const bound = (u,s,id=null)=>link.bindTrustedSkill(u,s,id);
assert.equal(link.physicalType("Contundente"),"blunt");
assert.equal(link.physicalType("Bludgeoning"),"blunt");
assert.equal(link.physicalType("Cortante"),"slash");
assert.equal(link.physicalType("Slashing"),"slash");
assert.equal(link.physicalType("Perforante"),"pierce");
assert.equal(link.physicalType("Piercing"),"pierce");
assert.equal(link.skillAvailability(unit,slash).available,true);
assert.equal(bound(unit,slash).bound,true);
assert.equal(bound(unit,slash).instanceId,"sw1");
assert.equal(link.skillAvailability(unit,blunt).available,false,"Mace Skill must not work with Slash sword");
assert.equal(link.skillAvailability(unit,blunt).reason,"weapon_damage_type_incompatible");
assert.equal(bound(unit,blunt).bound,false);
assert.equal(bound(unit,blunt,"sw1").reason,"weapon_damage_type_incompatible");
assert.equal(bound(unit,pierce).bound,false,"Piercing cannot use Slash sword");
assert.equal(link.compatibleWeapons(unit,blunt).length,0);
assert.equal(link.compatibleWeapons(unit,slash).length,1);
assert.equal(link.weaponSupportsSkill(blade,slash),true);
assert.equal(link.weaponSupportsSkill(blade,blunt),false);
const dual = {equipment:{mainHand:blade,offHand:mace}};
assert.deepEqual(link.compatibleWeapons(dual,blunt).map(w=>w.instanceId),["mc1"]);
assert.deepEqual(link.compatibleWeapons(dual,slash).map(w=>w.instanceId),["sw1"]);
assert.equal(bound(dual,blunt).instanceId,"mc1");
assert.equal(bound(dual,blunt,"sw1").bound,false,"Cannot force wrong weapon ID in plan");
assert.equal(bound(dual,pierce).bound,false);
const specialPommel = {...blunt,id:"pommel",compatibleWeaponDamageTypes:["slash"]};
assert.equal(bound(unit,specialPommel).bound,true,"Only explicitly authored unusual technique may use sword as Blunt");
assert.equal(specialPommel.damageType,"contundente","Skill type remains unchanged");
assert.equal(bound(unit,{...blunt,weaponUsage:"unarmed"}).bound,false);
assert.equal(link.skillAvailability(unit,{...blunt,weaponUsage:"unarmed"}).available,true);
assert.equal(link.skillAvailability(unit,{...blunt,isUnarmed:true}).available,true);
assert.equal(link.skillAvailability(unit,{type:"Spell",damageType:"contundente"}).available,true);
assert.equal(link.skillAvailability(unit,{type:"Defense",damageType:"contundente"}).available,true);
assert.equal(link.skillAvailability({equipment:{}},blunt).available,true,"Learned unarmed/default Skills still exist without weapons");
assert.equal(bound({equipment:{}},{...blunt,requiresWeapon:true}).bound,false,"Explicit weapon Skill requires gear");
assert.equal(link.skillAvailability({equipment:{}},{...slash,requiresWeapon:true}).available,false);
assert.equal(bound({equipment:{mainHand:dagger}},pierce).bound,true);
assert.equal(bound({equipment:{mainHand:blade,offHand:blade}},slash).bound,true,"Two-handed weapon reference deduped");
assert.equal(link.compatibleWeapons({equipment:{mainHand:blade,offHand:blade}},slash).length,1);
assert.equal(bound(dual,{...blunt,weaponSlot:"mainHand"}).bound,false);
assert.equal(bound(dual,{...blunt,weaponSlot:"offHand"}).instanceId,"mc1");
assert.equal(bound(dual,{...blunt,weaponDefinitionId:"longsword"}).bound,false);
assert.equal(bound(dual,{...slash,weaponDefinitionId:"longsword"}).bound,true);
assert.equal(link.weaponDamageTypes({damageTypes:["slash","blunt"]}).length,2);
assert.equal(link.weaponSupportsSkill({damageTypes:["slash","blunt"]},blunt),true);
assert.equal(link.weaponSupportsSkill({damageType:"magic"},blunt),false,"Unknown damage type cannot fake physical compatibility");
const player = {inventario_activo:{sword:blade,mace},itemEquipmentRefs:{mainHand:"sw1",offHand:"mc1"}};
const gear = link.resolveEquipment({},player);
assert.equal(link.skillAvailability({equipment:gear.equipment},blunt).available,true);
assert.deepEqual(link.compatibleWeapons({equipment:gear.equipment},blunt).map(x=>x.instanceId),["mc1"]);
assert.equal(link.isWeaponSkill({type:"Attack",damageType:"slash"}),false,"Existing learned/innate attack classification stays intact");
const root=path.resolve(__dirname,"..");
const adapter=fs.readFileSync(path.join(root,"js/battle-viewer-action-adapter-073.js"),"utf8");
const planner=fs.readFileSync(path.join(root,"js/battle-viewer-player-skill-planner-074.js"),"utf8");
const theatre=fs.readFileSync(path.join(root,"js/player-skills-hud.js"),"utf8");
const page=fs.readFileSync(path.join(root,"hoja_personaje.html"),"utf8");
assert.match(adapter,/link\.requiresEquippedWeapon\(actor, result\.skill\)/,"Action compilation must call trusted shared validator");
assert.match(planner,/link\.bindTrustedSkill\(source\.unit, trustedSkill, weaponInstanceId\)/,"Player planning validates authored Skill");
assert.match(planner,/weaponLink\.compatibleWeapons\(weaponContext\.unit, selectedRaw\)/,"Player only offered compatible weapons");
assert.match(theatre,/weaponLink\?\.skillAvailability\?\./,"Theatre character HUD uses identical validator");
assert.match(page,/js\/item-enchantment-combat-link\.js/);
console.log("WEAPON_SKILL_COMPAT_PASS Slash Blunt Pierce dual wield independent spell explicit overrides unified planning/execution/theatre");
